import { DataRow, AnomalyFinding, MetricSummary, ProductMetric, AIExplanation } from '../../types';
import { calculateProductMetrics, calculateDailyTrends } from './metrics';

export function detectAnomalies(
  rows: DataRow[],
  metrics: MetricSummary,
  hasCost: boolean,
  hasStock: boolean
): AnomalyFinding[] {
  if (rows.length < 5) {
    return [];
  }

  const findings: AnomalyFinding[] = [];
  const productMetrics = calculateProductMetrics(rows, hasStock);
  const dailyTrends = calculateDailyTrends(rows);

  // 1. Detect Surge in Product Demand
  // Group by product and compare early half vs late half of timeframe
  const midIndex = Math.floor(rows.length / 2);
  const earlyRows = rows.slice(0, midIndex);
  const lateRows = rows.slice(midIndex);

  const earlyProds = new Map<string, number>();
  const lateProds = new Map<string, number>();

  for (const r of earlyRows) {
    earlyProds.set(r.product, (earlyProds.get(r.product) || 0) + r.quantity);
  }
  for (const r of lateRows) {
    lateProds.set(r.product, (lateProds.get(r.product) || 0) + r.quantity);
  }

  for (const [prod, lateQty] of lateProds.entries()) {
    const earlyQty = earlyProds.get(prod) || 1;
    const deltaRatio = (lateQty - earlyQty) / earlyQty;

    if (deltaRatio >= 0.4 && lateQty >= 15) {
      const pct = (deltaRatio * 100).toFixed(1);
      findings.push({
        id: `ANOM-SURGE-${prod.toUpperCase().replace(/\s+/g, '_')}`,
        title: `Demand Velocity Surge: ${prod}`,
        type: 'surge',
        severity: 'info',
        metric: 'Units Sold (Late Window vs Early Window)',
        observedValue: `${lateQty} units`,
        baselineValue: `${earlyQty} units`,
        delta: `+${pct}%`,
        timeWindow: `${metrics.dateRange.start} — ${metrics.dateRange.end}`,
        description: `Product '${prod}' demonstrated a significant +${pct}% acceleration in sales volume between the first and second observation halves.`,
        evidence: [
          {
            key: 'Initial Period Volume',
            value: `${earlyQty} units`,
            explanation: `Units sold during the initial observation window (${metrics.dateRange.start} to mid-cycle).`,
          },
          {
            key: 'Recent Period Volume',
            value: `${lateQty} units`,
            explanation: `Units sold during recent observation window (mid-cycle to ${metrics.dateRange.end}).`,
          },
          {
            key: 'Total Product Revenue',
            value: `$${(productMetrics.find((p) => p.product === prod)?.revenue || 0).toLocaleString()}`,
            explanation: `Cumulative revenue generated by ${prod} across all recorded orders.`,
          },
          {
            key: 'Velocity Change',
            value: `+${pct}% acceleration`,
            explanation: `Calculated as: ((Recent Units - Initial Units) / Initial Units) * 100.`,
          },
        ],
        aiStatus: 'idle',
        aiSource: 'unconfigured',
      });
    }
  }

  // 2. Detect Critical Stockout Risk
  if (hasStock) {
    for (const pm of productMetrics) {
      if (
        pm.stockOnHand !== null &&
        pm.stockOnHand !== undefined &&
        pm.runOutDays !== null &&
        pm.runOutDays !== undefined
      ) {
        if (pm.runOutDays <= 7 || (pm.stockOnHand <= 20 && pm.unitsSold >= 10)) {
          findings.push({
            id: `ANOM-STOCK-${pm.product.toUpperCase().replace(/\s+/g, '_')}`,
            title: `Impending Stockout Risk: ${pm.product}`,
            type: 'stockout_risk',
            severity: 'critical',
            metric: 'Days of Inventory Remaining',
            observedValue: `${pm.runOutDays} days`,
            baselineValue: '14.0 days safe buffer',
            delta: `-${Math.max(0, Math.round(14 - pm.runOutDays))} days below buffer`,
            timeWindow: `Current snapshot as of ${metrics.dateRange.end}`,
            description: `At the observed sales velocity (${(pm.unitsSold / Math.max(1, dailyTrends.length)).toFixed(1)} units/day), stock for '${pm.product}' is projected to deplete within ${pm.runOutDays} days without replenishment.`,
            evidence: [
              {
                key: 'Stock on Hand',
                value: `${pm.stockOnHand} units`,
                explanation: 'Most recent reported physical stock inventory count.',
              },
              {
                key: 'Historical Run Rate',
                value: `${(pm.unitsSold / Math.max(1, dailyTrends.length)).toFixed(2)} units/day`,
                explanation: `Total units sold (${pm.unitsSold}) divided by ${dailyTrends.length} distinct days in active window.`,
              },
              {
                key: 'Depletion Runway',
                value: `${pm.runOutDays} days`,
                explanation: 'Calculated as: Current Stock on Hand / Average Daily Unit Velocity.',
              },
              {
                key: 'Recommended Safe Buffer',
                value: '14 days',
                explanation: 'Standard small-business supplier lead time + 3-day buffer.',
              },
            ],
            aiStatus: 'idle',
            aiSource: 'unconfigured',
          });
        }
      }
    }
  }

  // 3. Detect Demand Velocity Drop
  for (const [prod, lateQty] of lateProds.entries()) {
    const earlyQty = earlyProds.get(prod) || 0;
    if (earlyQty >= 10 && lateQty < earlyQty * 0.6) {
      const dropPct = (((earlyQty - lateQty) / earlyQty) * 100).toFixed(1);
      findings.push({
        id: `ANOM-DROP-${prod.toUpperCase().replace(/\s+/g, '_')}`,
        title: `Demand Velocity Contraction: ${prod}`,
        type: 'drop',
        severity: 'warning',
        metric: 'Sales Velocity Contraction',
        observedValue: `${lateQty} units`,
        baselineValue: `${earlyQty} units`,
        delta: `-${dropPct}%`,
        timeWindow: `${metrics.dateRange.start} — ${metrics.dateRange.end}`,
        description: `'${prod}' experienced a -${dropPct}% drop in units sold during the second half of the period.`,
        evidence: [
          {
            key: 'Baseline Volume',
            value: `${earlyQty} units`,
            explanation: 'Sales recorded in the early sample window.',
          },
          {
            key: 'Recent Volume',
            value: `${lateQty} units`,
            explanation: 'Sales recorded in the late sample window.',
          },
          {
            key: 'Contraction Magnitude',
            value: `-${dropPct}%`,
            explanation: 'Calculated as: ((Early Units - Recent Units) / Early Units) * 100.',
          },
        ],
        aiStatus: 'idle',
        aiSource: 'unconfigured',
      });
    }
  }

  // 4. Detect Margin Anomaly (if cost exists)
  if (hasCost && metrics.grossMarginPercent !== null && metrics.grossMarginPercent !== undefined) {
    const portfolioMargin = metrics.grossMarginPercent;
    const categoryMargins = new Map<string, { totalRev: number; totalCost: number }>();
    for (const r of rows) {
      if (r.cost !== null && r.cost !== undefined) {
        const cat = categoryMargins.get(r.category) || { totalRev: 0, totalCost: 0 };
        cat.totalRev += r.revenue;
        cat.totalCost += r.cost;
        categoryMargins.set(r.category, cat);
      }
    }

    for (const [cat, data] of categoryMargins.entries()) {
      const catMargin = data.totalRev > 0 ? ((data.totalRev - data.totalCost) / data.totalRev) * 100 : 0;
      if (catMargin < portfolioMargin - 8) {
        findings.push({
          id: `ANOM-MARGIN-${cat.toUpperCase()}`,
          title: `Sub-Benchmark Gross Margin: Category '${cat}'`,
          type: 'margin_leak',
          severity: 'warning',
          metric: 'Category Margin vs Overall Portfolio Margin',
          observedValue: `${catMargin.toFixed(1)}%`,
          baselineValue: `${portfolioMargin.toFixed(1)}% portfolio avg`,
          delta: `-${(portfolioMargin - catMargin).toFixed(1)}% margin spread`,
          timeWindow: 'Entire active dataset window',
          description: `Category '${cat}' generates a gross margin of ${catMargin.toFixed(
            1
          )}%, trailing the store portfolio average of ${portfolioMargin.toFixed(1)}%.`,
          evidence: [
            {
              key: 'Category Revenue',
              value: `$${Math.round(data.totalRev).toLocaleString()}`,
              explanation: `Total gross revenue earned in category '${cat}'.`,
            },
            {
              key: 'Category Cost of Goods',
              value: `$${Math.round(data.totalCost).toLocaleString()}`,
              explanation: 'Total cost incurred for goods sold in this category.',
            },
            {
              key: 'Category Gross Margin',
              value: `${catMargin.toFixed(1)}%`,
              explanation: 'Calculated as: ((Revenue - Cost) / Revenue) * 100.',
            },
            {
              key: 'Portfolio Baseline Margin',
              value: `${portfolioMargin.toFixed(1)}%`,
              explanation: 'Store-wide gross margin across all categories.',
            },
          ],
          aiStatus: 'idle',
          aiSource: 'unconfigured',
        });
      }
    }
  }

  return findings;
}

// Deterministic rule-based fallback generator
export function generateDeterministicFallbackExplanation(finding: AnomalyFinding): AIExplanation {
  const isStockout = finding.type === 'stockout_risk';
  const isSurge = finding.type === 'surge';
  const isDrop = finding.type === 'drop';
  const isMargin = finding.type === 'margin_leak';

  let summary = '';
  let whyItMatters = '';
  const underlyingDrivers: string[] = [];
  const recommendedActions = [];

  if (isStockout) {
    summary = `Rule engine detected inventory runout runway of ${finding.observedValue} based on linear daily velocity.`;
    whyItMatters =
      'Running out of stock halts top-line revenue for this SKU and risks disappointing recurring customers.';
    underlyingDrivers.push('Current stock quantity is near or below safety buffer threshold.');
    underlyingDrivers.push('Consistent customer ordering rate without recent supplier replenishment receipts.');
    recommendedActions.push({
      actionId: `ACT-${finding.id}-REORDER`,
      title: 'Initiate Supplier Restock Order (Simulated)',
      description: 'Generate purchase requisition for 50 units with standard 7-day supplier SLA.',
      expectedImpact: 'Extends inventory depletion runway from current days to 25+ days.',
      actionType: 'restock' as const,
      targetEntity: finding.title.split(': ')[1] || 'Target Product',
      parameters: { suggestedUnits: 50, priority: 'High' },
    });
    recommendedActions.push({
      actionId: `ACT-${finding.id}-PRICE`,
      title: 'Modulate Temporary Unit Price (+5%)',
      description: 'Temporarily increase price slightly to preserve margin and moderate run rate until delivery.',
      expectedImpact: 'Slightly paces run rate while protecting gross profit.',
      actionType: 'price_adjust' as const,
      targetEntity: finding.title.split(': ')[1] || 'Target Product',
      parameters: { priceAdjustmentPct: 5 },
    });
  } else if (isSurge) {
    summary = `Statistically verified demand surge of ${finding.delta} observed over the timeframe.`;
    whyItMatters =
      'High product momentum indicates strong product-market resonance and presents cross-sell potential.';
    underlyingDrivers.push('Accelerated customer order volume and increased repeat cart placements.');
    underlyingDrivers.push('Product price point and category appeal driving healthy conversion.');
    recommendedActions.push({
      actionId: `ACT-${finding.id}-PROMO`,
      title: 'Feature on Storefront Banner (Simulated)',
      description: 'Highlight high-velocity product on main digital showcase to capitalize on momentum.',
      expectedImpact: 'Projected +10-15% incremental orders during sustained cycle.',
      actionType: 'promotion' as const,
      targetEntity: finding.title.split(': ')[1] || 'Target Product',
    });
    recommendedActions.push({
      actionId: `ACT-${finding.id}-SAFETY`,
      title: 'Review Upstream Reorder Point',
      description: 'Audit supplier minimum lead times to ensure incoming supplier pipeline sustains velocity.',
      expectedImpact: 'Prevents unexpected stock bottlenecks during demand peaks.',
      actionType: 'investigation' as const,
      targetEntity: finding.title.split(': ')[1] || 'Target Product',
    });
  } else if (isDrop) {
    summary = `Observed demand slowdown of ${finding.delta} between observation windows.`;
    whyItMatters =
      'Unresolved velocity deceleration can lead to dead inventory carrying costs and lost category revenue.';
    underlyingDrivers.push('Purchasing slowdown or end of seasonal buying wave.');
    underlyingDrivers.push('Potential price sensitivity or competitor offering.');
    recommendedActions.push({
      actionId: `ACT-${finding.id}-INVESTIGATE`,
      title: 'Conduct Customer Price & Basket Review',
      description: 'Inspect order logs to examine whether cart drop-offs correspond to price changes.',
      expectedImpact: 'Identifies clear root causes for conversion decay.',
      actionType: 'investigation' as const,
      targetEntity: finding.title.split(': ')[1] || 'Target Product',
    });
    recommendedActions.push({
      actionId: `ACT-${finding.id}-DISCOUNT`,
      title: 'Bundle with High-Velocity Complementary SKU',
      description: 'Create a simulated bundled offer pairing this SKU with a top seller at a 10% bundle discount.',
      expectedImpact: 'Re-ignites unit sales velocity and liquidates aging stock.',
      actionType: 'promotion' as const,
      targetEntity: finding.title.split(': ')[1] || 'Target Product',
    });
  } else if (isMargin) {
    summary = `Gross margin of ${finding.observedValue} falls noticeably below portfolio benchmark (${finding.baselineValue}).`;
    whyItMatters =
      'Products or categories generating substantial volume at weak margins dilute overall business net profitability.';
    underlyingDrivers.push('Supplier unit cost comprises higher percentage of selling price.');
    underlyingDrivers.push('Lack of price adjustment in response to supplier cost adjustments.');
    recommendedActions.push({
      actionId: `ACT-${finding.id}-MARGIN-PRICE`,
      title: 'Simulate +7% Strategic Price Readjustment',
      description: 'Model a selective price adjustment on low-elasticity items in this category.',
      expectedImpact: 'Brings category margin closer to store benchmark (+3.5% gain).',
      actionType: 'price_adjust' as const,
      targetEntity: finding.title.split(': ')[1] || 'Target Category',
      parameters: { priceAdjustmentPct: 7 },
    });
  } else {
    summary = `Deterministic rule flag for ${finding.metric}: ${finding.observedValue} vs ${finding.baselineValue}.`;
    whyItMatters = 'Metrics deviate beyond standard statistical tolerances.';
    underlyingDrivers.push('Data points show atypical concentration or variance.');
    recommendedActions.push({
      actionId: `ACT-${finding.id}-AUDIT`,
      title: 'Inspect Raw Order Data Entries',
      description: 'Filter explorer table to inspect raw timestamps and quantity spikes.',
      expectedImpact: 'Validates data integrity before operational changes.',
      actionType: 'investigation' as const,
      targetEntity: 'Selected Metric Data',
    });
  }

  return {
    findingId: finding.id,
    summary,
    whyItMatters,
    underlyingDrivers,
    uncertaintyNotes:
      'Deterministic rule-based baseline model. Does not factor in external macro seasonality or supplier contract changes. Review before applying business adjustments.',
    recommendedActions,
    generatedAt: new Date().toISOString(),
    providerLabel: 'SignalForge Deterministic Rule Engine (Honest Fallback)',
    isFallback: true,
  };
}
